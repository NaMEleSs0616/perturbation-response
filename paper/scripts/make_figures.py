def tex_name(key: str) -> str:
    """'replogle2022_k562_essential' -> 'ReplogleKEssential', 'betaIvMedian' -> 'BetaIvMedian' (TeX names are letters only)."""
    return "".join(ch for part in key.split("_") for ch in (part[:1].upper() + part[1:]) if ch.isalpha())


class Numbers:
    def __init__(self):
        self.items: dict[str, str] = {}

    def add(self, key: str, value, fmt: str = "{:.2f}") -> None:
        self.items[key] = value if isinstance(value, str) else fmt.format(value)

    def write(self, path: Path) -> None:
        lines = ["% Generated by paper/scripts/make_figures.py; do not edit."]
        lines += [f"\\newcommand{{\\num{tex_name(k)}}}{{{v}}}" for k, v in sorted(self.items.items())]
        path.write_text("\n".join(lines) + "\n")


def load_study(study: Path) -> dict:
    meta = json.loads((study / "study.json").read_text())
    datasets = json.loads((study / "datasets.json").read_text())
    included = [d["dataset_id"] for d in datasets if d.get("included")]
    frame = pd.read_csv(study / "per_perturbation_all.csv")
    ceil = pd.concat([pd.read_csv(study / d / "noise_ceiling.csv") for d in included], ignore_index=True)
    cal = pd.concat([pd.read_csv(study / d / "metric_calibration.csv") for d in included], ignore_index=True)
    rank = pd.concat([pd.read_csv(study / d / "ranking.csv") for d in included], ignore_index=True)
    return {"meta": meta, "datasets": datasets, "included": included, "frame": frame, "ceil": ceil, "cal": cal, "rank": rank,
            "confirm": pd.read_csv(study / "confirmatory_tests.csv"), "discovery": pd.read_csv(study / "discovery_tests.csv"),
            "lc": pd.read_csv(study / "learning_curve.csv") if (study / "learning_curve.csv").exists() else None,
            "cc": pd.read_csv(study / "cross_context.csv") if (study / "cross_context.csv").exists() else None}


def primary(frame: pd.DataFrame, seed: int = 0) -> pd.DataFrame:
    d = frame[(frame["stratum"] == "single_unseen") & (frame["split_seed"] == seed)]
    num = ["mse", "skill_vs_mean", "pearson_specific", "spearman_specific", "pearson", "coverage", "coverage_top", "rmse", "disagreement"]
    num = [c for c in num if c in d]
    return d.groupby(["dataset_id", "variant", "model", "condition"], as_index=False, observed=True)[num].mean()


def order(ids: list[str]) -> list[str]:
    pref = ["norman2019", "replogle2022_k562_essential", "replogle2022_rpe1", "tian2021_crispra", "tian2021_crispri"]
    return [d for d in pref if d in ids] + [d for d in ids if d not in pref]


def fig_skill(S: dict, out: Path, N: Numbers) -> None:
    """Forest plot on unseen genes: learned models (blue) and uninformative controls (grey)."""
    p = primary(S["frame"])
    entries = [("coexpression", "ridge", "Ridge", BLUE), ("coexpression", "gene_loading_ridge", "Gene-loading ridge", BLUE), ("coexpression", "mlp_ensemble", "MLP ensemble", BLUE),
               ("shuffled_coexpression", "mlp_ensemble", "MLP, permuted features", MUTED), ("coexpression", "zero", "Zero (no change)", MUTED)]
    ds = order(S["included"])
    fig, axes = plt.subplots(1, 2, figsize=(7.4, 0.9 + 0.78 * len(ds) * len(entries) / 4), gridspec_kw={"width_ratios": [1.1, 1]}, sharey=True)
    rows, y = [], 0
    for d in ds:
        for v, m, label, col in entries:
            g = p[(p["dataset_id"] == d) & (p["variant"] == v) & (p["model"] == m)]
            if g.empty:
                continue
            rows.append((y, d, label, col, bootstrap_ci(g["skill_vs_mean"].to_numpy()), bootstrap_ci(g["pearson_specific"].to_numpy())))
            y -= 1
        y -= 0.9
    for yy, d, label, col, sk, ps in rows:
        for ax, ci in ((axes[0], sk), (axes[1], ps)):
            ax.plot([ci[1], ci[2]], [yy, yy], color=col, lw=1.6, solid_capstyle="round")
            ax.plot(ci[0], yy, "o", color=col, ms=4)
    cm = S["ceil"][S["ceil"]["stratum"] == "single_unseen"].groupby(["dataset_id", "condition"], observed=True).mean(numeric_only=True).groupby("dataset_id").mean()
    for d in ds:
        ys = [r[0] for r in rows if r[1] == d]
        axes[0].text(0.0, max(ys) + 0.62, NAMES.get(d, d), transform=axes[0].get_yaxis_transform(), ha="left", va="bottom", fontsize=7.5, fontweight="bold", color=INK)
        c = cm.loc[d, "specific_batch_max_r"]
        axes[1].plot([c, c], [min(ys) - 0.4, max(ys) + 0.4], color=ORANGE, lw=1.4, ls=(0, (3, 2)))
    for ax in axes:
        ax.axvline(0, color=INK, lw=0.8)
    axes[0].set_yticks([r[0] for r in rows], [r[2] for r in rows])
    axes[0].set_xlabel("Skill vs mean baseline  (1 − SSE/SSE$_{mean}$)")
    axes[1].set_xlabel("Pearson r, perturbation-specific response")
    axes[0].set_title("a  Skill relative to the mean baseline", loc="left", pad=16)
    axes[1].set_title("b  Specific correlation; dashed: technical reproducibility limit", loc="left", pad=16)
    axes[1].set_xlim(-0.2, 1.0)
    fig.tight_layout()
    fig.savefig(out / "fig2_unseen_genes.pdf")
    plt.close(fig)


def fig_learning_curve(S: dict, out: Path) -> None:
    lc = S["lc"]
    if lc is None:
        return
    lc = lc.copy()
    # each fold's full training set differs by a few conditions; plot them at one shared position per dataset
    fold_max = lc.groupby(["dataset_id", "fold"])["n_train"].transform("max")
    full = lc.assign(fm=fold_max).groupby("dataset_id")["fm"].transform("mean").round()
    lc["n_plot"] = np.where(lc["n_train"] == fold_max, full, lc["n_train"])
    ds = order(lc["dataset_id"].unique().tolist())
    fig, axes = plt.subplots(2, len(ds), figsize=(3.5 * len(ds), 4.6), sharex="col", squeeze=False)
    for j, d in enumerate(ds):
        g = lc[lc["dataset_id"] == d]
        for i, (metric, ylabel) in enumerate((("skill_vs_mean", "Skill vs mean"), ("pearson_specific", "r, specific response"))):
            ax = axes[i][j]
            for m, col in (("ridge", BLUE), ("gene_loading_ridge", ORANGE)):
                h = g[g["model"] == m].groupby(["n_plot", "repeat", "fold"], as_index=False)[metric].mean()
                assert h.groupby("n_plot")["fold"].nunique().min() >= len(g["fold"].unique()), "each size should pool every fold"
                st = h.groupby("n_plot")[metric].agg(["mean", "std", "count"]).reset_index()
                se = st["std"].fillna(0) / np.sqrt(st["count"])
                ax.fill_between(st["n_plot"], st["mean"] - 1.96 * se, st["mean"] + 1.96 * se, color=col, alpha=0.15, lw=0)
                ax.plot(st["n_plot"], st["mean"], "-o", color=col, ms=3.2, lw=1.6)
                if j == len(ds) - 1:
                    # keep the two end labels apart when the lines finish close together
                    ends = {mm: g[g["model"] == mm].groupby("n_plot")[metric].mean().iloc[-1] for mm in ("ridge", "gene_loading_ridge")}
                    above = ends[m] >= ends["ridge" if m == "gene_loading_ridge" else "gene_loading_ridge"]
                    ax.annotate(MODEL_NAMES[m], (st["n_plot"].iloc[-1], st["mean"].iloc[-1]), xytext=(5, 5 if above else -5), textcoords="offset points", fontsize=7, color=col, va="center")
            ax.axhline(0, color=INK, lw=0.8)
            ax.set_xscale("log", base=2)
            if j == 0:
                ax.set_ylabel(ylabel)
            if i == 0:
                ax.set_title(NAMES.get(d, d), loc="left")
            else:
                ax.set_xlabel("Training perturbations")
    fig.tight_layout()
    fig.savefig(out / "fig3_training_size.pdf")
    plt.close(fig)


def fig_cross_context(S: dict, out: Path) -> pd.DataFrame:
    """Measured response in the other cell line vs the unseen-gene MLP, on the same targets and genes."""
    cc = S["cc"]
    if cc is None:
        return pd.DataFrame()
    p = primary(S["frame"])
    mlp = p[(p["variant"] == "coexpression") & (p["model"] == "mlp_ensemble")].set_index(["dataset_id", "condition"])
    fig, axes = plt.subplots(1, 2, figsize=(7.2, 2.3), sharey=True)
    rows, y, records = [], 0, []
    for (src, dst), g in cc.groupby(["source", "target_dataset"]):
        targets = g["target"].unique()
        mlp_g = mlp.loc[dst].reindex(targets).dropna(subset=["skill_vs_mean"])
        items = [("Unseen-gene MLP (same targets)", mlp_g, GRID)]
        for pname, label in (("transfer_deviation_scaled", "Other cell line, rescaled"), ("transfer_raw", "Other cell line, raw")):
            items.append((label, g[g["predictor"] == pname], None))
        for label, h, _ in items:
            sk, ps = bootstrap_ci(h["skill_vs_mean"].to_numpy()), bootstrap_ci(h["pearson_specific"].to_numpy())
            col = BLUE if "rescaled" in label else (MUTED if "raw" in label else INK)
            rows.append((y, f"{NAMES[dst].split()[1]} target: {label}", col, sk, ps))
            records.append({"source": src, "target_dataset": dst, "predictor": label, "n": len(h), "skill": sk[0], "skill_lo": sk[1], "skill_hi": sk[2], "r_specific": ps[0]})
            y -= 1
        y -= 0.6
    for yy, label, col, sk, ps in rows:
        lo, hi = max(sk[1], -1.0), sk[2]
        axes[0].plot([lo, hi], [yy, yy], color=col, lw=1.6)
        if sk[0] >= -1.0:
            axes[0].plot(sk[0], yy, "o", color=col, ms=4)
        else:
            axes[0].annotate(f"← mean {sk[0]:.2f}", (-1.0, yy), xytext=(2, 3), textcoords="offset points", fontsize=6.5, color=col)
        axes[1].plot([ps[1], ps[2]], [yy, yy], color=col, lw=1.6)
        axes[1].plot(ps[0], yy, "o", color=col, ms=4)
    for ax in axes:
        ax.axvline(0, color=INK, lw=0.8)
    axes[0].set_xlim(-1.05, 0.15)
    axes[0].set_yticks([r[0] for r in rows], [r[1] for r in rows])
    axes[0].set_xlabel("Skill vs target screen's mean")
    axes[1].set_xlabel("r, specific response")
    axes[0].set_title("a", loc="left")
    axes[1].set_title("b", loc="left")
    fig.tight_layout()
    fig.savefig(out / "fig4_cross_context.pdf")
    plt.close(fig)
    return pd.DataFrame(records)



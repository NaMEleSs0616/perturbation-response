def fig_calibration(S: dict, out: Path, posthoc: Path | None) -> pd.DataFrame:
    cal = S["cal"]
    metrics = ["mse", "skill_vs_mean", "pearson", "pearson_specific", "spearman_specific", "topk_recall"]
    names = {"mse": "MSE", "skill_vs_mean": "Skill", "pearson": "r (raw)", "pearson_specific": "r (specific)", "spearman_specific": "ρ (specific)", "topk_recall": "Top-20 recall"}
    ds = order(S["included"])
    M = np.array([[cal[cal["dataset_id"] == d][f"{m}_duplicate_wins"].mean() for m in metrics] for d in ds])
    panels = [("a  Duplicate vs mean (pre-specified)", M)]
    if posthoc is not None and posthoc.exists():
        ph = pd.read_csv(posthoc)
        panels.append(("b  Duplicate vs best of mean and zero (post hoc)", np.array([[ph[ph["dataset_id"] == d][f"{m}_beats_best_uninformative"].mean() for m in metrics] for d in ds])))
    fig, axes = plt.subplots(1, len(panels), figsize=(4.0 * len(panels) + 0.8, 0.42 * len(ds) + 1.3), sharey=True, squeeze=False)
    for ax, (title, A) in zip(axes[0], panels):
        im = ax.imshow(A, cmap="Blues", vmin=0, vmax=1, aspect="auto")
        for i in range(len(ds)):
            for j in range(len(metrics)):
                ax.text(j, i, f"{A[i, j]:.2f}", ha="center", va="center", fontsize=6.8, color="white" if A[i, j] > 0.6 else INK)
        ax.set_xticks(range(len(metrics)), [names[m] for m in metrics], rotation=35, ha="right")
        ax.set_yticks(range(len(ds)), [NAMES.get(d, d) for d in ds])
        ax.set_title(title, loc="left")
        ax.grid(False)
    cb = fig.colorbar(im, ax=axes[0].tolist(), fraction=0.025, pad=0.02)
    cb.set_label("Fraction of perturbations where a\ntechnical duplicate wins", fontsize=7)
    fig.savefig(out / "fig6_calibration.pdf")
    plt.close(fig)
    return pd.DataFrame(M, index=ds, columns=metrics)


def numbers(S: dict, bench: Path, pairs: Path, cal: pd.DataFrame, N: Numbers) -> pd.DataFrame:
    p = primary(S["frame"])
    co = p[p["variant"] == "coexpression"]
    N.add("planShaShort", S["meta"]["plan_sha256"][:8])
    ds = order(S["included"])
    N.add("nDatasetsIncluded", str(len(ds)))
    N.add("nConfirmation", str(len([d for d in ds if d != "norman2019"])))
    N.add("nPerturbationsTotal", f"{int(co[co['model'] == 'mean']['condition'].count()):,}")
    rows = []
    for d in ds:
        k = tex_name(d)
        g = co[co["dataset_id"] == d]
        N.add(f"n{k}", f"{g[g['model'] == 'mean']['condition'].nunique():,}")
        for m in ["ridge", "gene_loading_ridge", "mlp_ensemble", "knn"]:
            h = g[g["model"] == m]
            if h.empty:
                continue
            sk = bootstrap_ci(h["skill_vs_mean"].to_numpy())
            N.add(f"skill{k}{tex_name(m)}", sk[0], "{:.3f}")
            N.add(f"skillLo{k}{tex_name(m)}", sk[1], "{:.3f}")
            N.add(f"skillHi{k}{tex_name(m)}", sk[2], "{:.3f}")
            N.add(f"spec{k}{tex_name(m)}", float(h["pearson_specific"].mean()))
            rows.append({"dataset": d, "model": m, "skill": sk[0], "skill_lo": sk[1], "skill_hi": sk[2], "median_skill": float(h["skill_vs_mean"].median()),
                         "r_specific": float(h["pearson_specific"].mean()), "r_raw": float(h["pearson"].mean()), "frac_positive_skill": float((h["skill_vs_mean"] > 0).mean())})
        N.add(f"rawMean{k}", float(g[g["model"] == "mean"]["pearson"].mean()))
        z = g[g["model"] == "zero"]
        N.add(f"zeroSkill{k}", float(z["skill_vs_mean"].mean()), "{:.2f}")
        N.add(f"zeroSpec{k}", float(z["pearson_specific"].mean()))
        sh = p[(p["dataset_id"] == d) & (p["variant"] == "shuffled_coexpression")]
        for m in ["ridge", "mlp_ensemble"]:
            N.add(f"shufSpec{k}{tex_name(m)}", float(sh[sh["model"] == m]["pearson_specific"].mean()))
            N.add(f"shufSkill{k}{tex_name(m)}", float(sh[sh["model"] == m]["skill_vs_mean"].mean()), "{:.3f}")
        g2 = p[(p["dataset_id"] == d) & (p["variant"] == "gene2vec")]
        for m in ["ridge", "mlp_ensemble"]:
            N.add(f"gvSpec{k}{tex_name(m)}", float(g2[g2["model"] == m]["pearson_specific"].mean()))
            N.add(f"gvSkill{k}{tex_name(m)}", float(g2[g2["model"] == m]["skill_vs_mean"].mean()), "{:.3f}")
        # post-hoc sensitivity: perturbations whose specific response reproduces across batch sets (r >= 0.5)
        cr = S["ceil"][(S["ceil"]["dataset_id"] == d) & (S["ceil"]["stratum"] == "single_unseen")].groupby("condition")["specific_batch_r"].mean()
        rep = set(cr[cr >= 0.5].index)
        N.add(f"nRepro{k}", f"{len(rep):,}")
        N.add(f"fracRepro{k}", f"{100 * len(rep) / max(len(cr), 1):.0f}")
        for v, m, key in (("coexpression", "mlp_ensemble", "Mlp"), ("coexpression", "ridge", "Ridge"), ("shuffled_coexpression", "mlp_ensemble", "ShufMlp"), ("coexpression", "zero", "Zero")):
            h = p[(p["dataset_id"] == d) & (p["variant"] == v) & (p["model"] == m) & (p["condition"].isin(rep))]
            if len(h):
                N.add(f"repSkill{k}{key}", float(h["skill_vs_mean"].mean()), "{:.3f}")
                N.add(f"repSpec{k}{key}", float(h["pearson_specific"].mean()))
        c = S["ceil"][(S["ceil"]["dataset_id"] == d) & (S["ceil"]["stratum"] == "single_unseen")].groupby("condition").mean(numeric_only=True)
        N.add(f"ceilBatch{k}", float(c["specific_batch_max_r"].mean()) if c["specific_batch_max_r"].notna().any() else float("nan"))
        N.add(f"ceilHalf{k}", float(c["specific_max_r"].mean()))
        N.add(f"reproBatch{k}", float(c["specific_batch_r"].mean()) if c["specific_batch_r"].notna().any() else float("nan"))
        rk = S["rank"][(S["rank"]["dataset_id"] == d)].set_index("ranking")
        for m in ["mlp_ensemble", "ridge"]:
            if m in rk.index:
                N.add(f"prec{k}{tex_name(m)}", float(rk.loc[m, "precision_at_k"]))
        for m in ["mse", "skill_vs_mean", "pearson", "pearson_specific", "spearman_specific"]:
            N.add(f"cal{k}{tex_name(m)}", float(cal.loc[d, m]))
        mlp = g[g["model"] == "mlp_ensemble"]
        if "coverage_top" in mlp:
            N.add(f"cov{k}", float(mlp["coverage"].mean()))
            N.add(f"covTop{k}", float(mlp["coverage_top"].mean()))
    ph_path = Path("results/paper/calibration_posthoc.csv")
    if ph_path.exists():
        ph = pd.read_csv(ph_path)
        for d in ds:
            for m in ["mse", "pearson", "pearson_specific", "topk_recall"]:
                N.add(f"calBest{tex_name(d)}{tex_name(m)}", float(ph[ph["dataset_id"] == d][f"{m}_beats_best_uninformative"].mean()))
    c = S["confirm"]
    c1 = c[c["test"] == "C1"]
    N.add("nCOneTests", str(len(c1)))
    N.add("nCOneBeat", str(int(np.nansum(c1["beats_mean"].astype(float)))))
    N.add("minCOnePHolm", float(c1["p_holm"].min()), "{:.2g}")
    c2 = c[c["test"] == "C2"]
    N.add("nCTwoInformative", str(int(np.nansum(c2["coexpression_informative"].astype(float)))))
    N.add("nCTwoTests", str(len(c2)))
    c3 = c[c["test"] == "C3"]
    N.add("nCThreeBetter", str(int(np.nansum(c3["gene2vec_better"].astype(float)))))
    N.add("nCThreeTests", str(len(c3)))
    t = pd.read_csv(pairs)
    rng = np.random.default_rng(0)
    meds = [np.median(t["beta_iv"].to_numpy()[rng.integers(0, len(t), len(t))]) for _ in range(2000)]
    N.add("betaIvMedian", float(t["beta_iv"].median()))
    N.add("betaIvLo", float(np.quantile(meds, 0.025)))
    N.add("betaIvHi", float(np.quantile(meds, 0.975)))
    N.add("betaOlsMedian", float(t["beta_ols"].median()))
    N.add("fracBelowOne", f"{100 * (t['beta_iv'] < 1).mean():.0f}")
    N.add("nPairs", str(len(t)))
    N.add("singlesReliability", float(t["singles_split_half_r"].median()))
    s = pd.read_csv(bench / "summary.csv")
    s = s[(s["stratum"] == "combo_seen_singles") & (s["subset"] == "all")]
    for m in ["additive", "scaled_additive", "ridge_on_additive", "mlp_on_additive", "additive_plus_mean_residual"]:
        for met, key in (("skill_vs_mean", "skill"), ("pearson_interaction", "inter"), ("pearson_specific", "spec")):
            r = s[(s["model"] == m) & (s["metric"] == met)]
            if len(r) and np.isfinite(r["mean"].iloc[0]):
                N.add(f"pair{key}{tex_name(m)}", float(r["mean"].iloc[0]))
    pc = pd.read_csv(bench / "paired_comparisons.csv")
    r = pc[(pc["stratum"] == "combo_seen_singles") & (pc["model"] == "mlp_on_additive") & (pc["reference"] == "scaled_additive") & (pc["metric"] == "mse")].iloc[0]
    N.add("pairMseDiffScaled", float(r["mean_diff"]), "{:.5f}")
    N.add("pairMseDiffScaledLo", float(r["ci_low"]), "{:.5f}")
    N.add("pairMseDiffScaledHi", float(r["ci_high"]), "{:.5f}")
    lc = S["lc"]
    if lc is not None:
        for d in lc["dataset_id"].unique():
            k = tex_name(d)
            for m in ["ridge", "gene_loading_ridge"]:
                g = lc[(lc["dataset_id"] == d) & (lc["model"] == m)]
                for n in sorted(g["n_train"].unique()):
                    pass
                full = g[g["n_train"] == g.groupby("fold")["n_train"].transform("max")]
                small = g[g["n_train"] == 100]
                N.add(f"lcFull{k}{tex_name(m)}", float(full["skill_vs_mean"].mean()))
                N.add(f"lcHundred{k}{tex_name(m)}", float(small["skill_vs_mean"].mean()) if len(small) else float("nan"))
                N.add(f"lcSpecFull{k}{tex_name(m)}", float(full["pearson_specific"].mean()))
    cc = S["cc"]
    if cc is not None:
        for (src, dst), g in cc.groupby(["source", "target_dataset"]):
            k = tex_name(f"{src.split('_')[1]}_to_{dst.split('_')[1]}")
            N.add(f"nShared{k}", str(g["target"].nunique()))
            for pname in ("transfer_raw", "transfer_deviation_scaled"):
                v = g[g["predictor"] == pname]
                ci = bootstrap_ci(v["skill_vs_mean"].to_numpy())
                N.add(f"cc{tex_name(pname)}{k}", ci[0], "{:.3f}")
                N.add(f"ccLo{tex_name(pname)}{k}", ci[1], "{:.3f}")
                N.add(f"ccHi{tex_name(pname)}{k}", ci[2], "{:.3f}")
                N.add(f"ccSpec{tex_name(pname)}{k}", float(v["pearson_specific"].mean()))
                N.add(f"ccFrac{tex_name(pname)}{k}", f"{100 * (v['skill_vs_mean'] > 0).mean():.0f}")
    return pd.DataFrame(rows)


def tex_escape(x: str) -> str:
    return str(x).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def fmt_p(p: float) -> str:
    if not np.isfinite(p):
        return "--"
    return f"{p:.2g}" if p >= 1e-3 else f"$<$0.001"


def tables(S: dict, bench: Path, study: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    # inclusion
    rows = []
    for d in S["datasets"]:
        inc = json.loads((study / d["dataset_id"] / "inclusion.json").read_text())
        summ = d if d.get("included") else {}
        rows.append(" & ".join([
            NAMES.get(d["dataset_id"], tex_escape(d["dataset_id"])),
            "Discovery" if d["dataset_id"] == "norman2019" else "Confirmation",
            "Included" if d.get("included") else "Excluded",
            f"{int(summ['n_conditions']):,}" if summ else "--",
            f"{int(summ['n_control_cells']):,}" if summ else (f"{int(inc['checks']['n_control_cells']):,}" if "n_control_cells" in inc["checks"] else "--"),
            f"{int(summ['n_batches'])}" if summ else "--",
            EXCLUSION_DETAIL.get(d["dataset_id"], tex_escape(inc["reason"])) if not d.get("included") else "",
        ]) + r" \\")
    (out / "inclusion.tex").write_text("\n".join([r"\begin{tabular}{llllrrp{4.3cm}}", r"\toprule",
        r"Dataset & Role & Status & Perturbations & Controls & Batches & Exclusion reason \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]))
    # confirmatory tests
    c = S["confirm"]
    rows = []
    for _, r in c[c["test"] == "C1"].iterrows():
        rows.append(f"{NAMES.get(r['dataset_id'], r['dataset_id'])} & {MODEL_NAMES[r['model']]} & {1e3 * r['mean_diff']:+.3f} ({1e3 * r['ci_low']:+.3f}, {1e3 * r['ci_high']:+.3f}) & {r['mean_skill']:.3f} & {fmt_p(r['p_raw'])} & {fmt_p(r['p_holm'])} & {'yes' if r['beats_mean'] == 1 else 'no'} \\\\")
    (out / "c1.tex").write_text("\n".join([r"\begin{tabular}{llcrrrc}", r"\toprule",
        r"Dataset & Model & $\Delta$MSE$\times10^{3}$ vs mean (95\% CI) & Skill & $p$ & $p_{\mathrm{Holm}}$ & Beats mean \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]))
    rows = []
    for t, label in (("C2", "Co-expression $-$ permuted"), ("C3", "Gene2vec $-$ co-expression")):
        for _, r in c[c["test"] == t].iterrows():
            flag = r["coexpression_informative"] if t == "C2" else r["gene2vec_better"]
            ph = fmt_p(r["p_holm"]) if t == "C3" else "--"
            rows.append(f"{t} & {label} & {NAMES.get(r['dataset_id'], r['dataset_id'])} & {MODEL_NAMES[r['model']]} & {r['mean_diff']:+.3f} ({r['ci_low']:+.3f}, {r['ci_high']:+.3f}) & {ph} & {'yes' if flag == 1 else 'no'} \\\\")
    (out / "c2c3.tex").write_text("\n".join([r"\begin{tabular}{lllllcc}", r"\toprule",
        r"Test & Contrast & Dataset & Model & Skill difference (95\% CI) & $p_{\mathrm{Holm}}$ & Supported \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]))
    # fold-partition robustness (D4)
    fr = S["frame"]
    fr = fr[(fr["stratum"] == "single_unseen") & (fr["variant"] == "coexpression") & fr["model"].isin(["ridge", "gene_loading_ridge", "mlp_ensemble"])]
    piv = fr.groupby(["dataset_id", "model", "split_seed"])["skill_vs_mean"].mean().unstack("split_seed")
    rows = [f"{NAMES.get(d, d)} & {MODEL_NAMES[m]} & " + " & ".join(f"{v:.3f}" for v in r.values) + r" \\" for (d, m), r in piv.reindex(order(S["included"]), level=0).iterrows()]
    (out / "seeds.tex").write_text("\n".join([r"\begin{tabular}{ll" + "r" * piv.shape[1] + "}", r"\toprule",
        r"Dataset & Model & " + " & ".join(f"Seed {c}" for c in piv.columns) + r" \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]))
    # discovery benchmark (Norman, single genes and pairs, trained with pairs)
    sm = pd.read_csv(bench / "summary.csv")
    sm = sm[sm["subset"] == "all"]
    rows = []
    for stratum, label in (("single_unseen", "Unseen single gene"), ("combo_one_unseen", "Pair, one gene unseen"), ("combo_seen_singles", "Pair, both singles measured")):
        g = sm[sm["stratum"] == stratum]
        for m in g["model"].unique():
            if m == "zero":
                continue
            k = g[(g["model"] == m) & (g["metric"] == "skill_vs_mean")].iloc[0]
            ps = g[(g["model"] == m) & (g["metric"] == "pearson_specific")]["mean"].iloc[0]
            rows.append((label, m, k["mean"], k["ci_low"], k["ci_high"], ps, int(k["n_perturbations"])))
    rows.sort(key=lambda r: (r[0], -r[2]))
    body, last = [], None
    for label, m, mean, lo, hi, ps, n in rows:
        body.append(f"{label if label != last else ''} & {tex_escape(m)} & {mean:.3f} ({lo:.3f}, {hi:.3f}) & {fmt(ps) if np.isfinite(ps) else '--'} & {n} \\\\")
        last = label
    (out / "discovery.tex").write_text("\n".join([r"\begin{tabular}{llccr}", r"\toprule",
        r"Stratum & Model & Skill vs mean (95\% CI) & $r$, specific & $n$ \\", r"\midrule", *body, r"\bottomrule", r"\end{tabular}"]))


